/**
 * The world with Nepal cut out of it.
 *
 * A fill with two rings: an outer box covering the whole map and Nepal as a
 * hole. GeoJSON winding rules do the rest, so the dimming is one layer rather
 * than four rectangles that never quite meet at the corners.
 */
interface PolygonFeature {
  type: "Feature";
  properties: Record<string, never>;
  geometry: { type: "Polygon"; coordinates: [number, number][][] };
}

export const OUTSIDE_NEPAL: PolygonFeature = {
  type: "Feature",
  properties: {},
  geometry: {
    type: "Polygon",
    coordinates: [
      // A REGIONAL box, not the whole world. A world-spanning polygon looked
      // correct in a pitched close-up and then vanished entirely when the
      // camera flattened and zoomed out — a polygon that big, carrying a
      // hole, does not survive being cut into tiles at low zoom, and it fails
      // by disappearing rather than by erroring. This reaches about 1,000 km
      // past every border, far beyond what these maps can show.
      [
        [68, 16],
        [100, 16],
        [100, 40],
        [68, 40],
        [68, 16],
      ],
      NEPAL_RING,
    ],
  },
};

/** Just the border, for the thin line that keeps the edge from reading as a crop. */
export const NEPAL_OUTLINE: PolygonFeature = {
  type: "Feature",
  properties: {},
  geometry: { type: "Polygon", coordinates: [NEPAL_RING] },
};
